import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdir,readFile} from 'node:fs/promises';
import {setup} from './helpers.js';
import {one} from './helpers.js';
import {processOne} from './helpers.js';
import {authLink} from './helpers.js';
import {existsSync} from 'node:fs';
import {chromium} from 'playwright';

test('browser + API + PostgreSQL: registration, verification, login, profile and password recovery',async t=>{
 const origin='http://127.0.0.1:3001';
 const env=await setup({APP_ORIGIN:origin,PORT:3001,DEV_MAIL_PATH:'.local/e2e-mail'});
 t.after(env.close);
 await env.app.listen({host:'127.0.0.1',port:3001});
 const chromePath=process.env.E2E_BROWSER_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe';
 const browser=await chromium.launch(existsSync(chromePath)?{executablePath:chromePath}:{});
 t.after(()=>browser.close());
 const page=await browser.newPage({locale:'pt-BR',viewport:{width:1440,height:1000}});
 await page.route('https://*.openstreetmap.org/**',route=>route.abort());
 const errors:string[]=[];
 page.on('pageerror',(error:Error)=>errors.push(error.message));
 page.setDefaultTimeout(10000);
 const email='browser-student@example.com',password='Senha-navegador-2026'; // gitleaks:allow -- synthetic fixture, never used by production.
 await page.goto(origin+'/dashboard.html');
 await page.waitForURL('**/login.html#login');
 await page.getByRole('link',{name:'Criar conta',exact:true}).click();
 await page.locator('#signup-name').fill('Estudante Navegador');
 await page.locator('#signup-email').fill(email);
 await page.locator('#signup-password').fill(password);
 await page.locator('#signup-confirm').fill(password);
 await page.locator('#signup-birth').fill('2000-05-01');
 await page.locator('#signup-truth').check();
 await page.locator('#signup-terms').check();await page.locator('#signup-privacy').check();
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.locator('#signup-course').fill('Análise');
 await page.getByRole('option',{name:'Análise e Desenvolvimento de Sistemas',exact:true}).click();
 await page.locator('#signup-period').fill('3');
 await page.locator('#signup-shift').selectOption('night');
 await page.locator('#signup-class').selectOption('A');
 await page.locator('#signup-neighborhood').fill('Gama');
 await page.getByRole('option',{name:'Gama',exact:true}).click();
 await page.locator('#signup-phone').fill('61999990000');
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.getByRole('heading',{name:'Confirme seu e-mail.',exact:true}).waitFor();
 const visualRoot='docs/previews/java-connected';
 await mkdir(visualRoot,{recursive:true});
 for(const [label,width,height] of [['desktop',1440,900],['notebook',1280,720],['tablet',768,1024],['mobile',390,844]] as const){
  await page.setViewportSize({width,height});
  await page.screenshot({path:visualRoot+'/auth-confirmation-registered-'+label+'.png',fullPage:true});
 }
 await page.setViewportSize({width:1440,height:1000});
 const account=await one(env.pool,'SELECT id,email_verified_at FROM users WHERE email=$1',[email]);
 assert.ok(account);
 assert.equal(account.email_verified_at,null);
 assert.equal(await page.locator('#confirm-email-demo').count(),0);
 assert.equal(await page.evaluate(()=>localStorage.length),0);
 // Confirmation must remain usable after a reload loses the in-memory signup draft.
 await page.reload();
 await page.getByRole('heading',{name:'Confirme seu e-mail.',exact:true}).waitFor();
 await page.locator('#resend-form').waitFor();
 assert.equal(await page.locator('#email').getAttribute('type'),'email');
 await page.locator('#email').fill(email);
 assert.equal(await page.getByRole('button',{name:'Solicitar outro link',exact:true}).isEnabled(),true);
 const verification=await one(env.pool,"SELECT * FROM outbox_jobs WHERE type='email' AND payload->>'ownerId'=(SELECT id::text FROM users WHERE email=$1) AND payload->>'kind'='verify_email' ORDER BY created_at DESC LIMIT 1",[email]);
 assert.ok(await processOne(env.pool,env.config));
 const mail=JSON.parse(await readFile(env.config.DEV_MAIL_PATH+'/'+verification!.id+'.json','utf8'));
 await page.goto(mail.url);
 await page.getByRole('heading',{name:'E-mail confirmado.',exact:true}).waitFor();
 assert.equal(new URL(page.url()).hash,'#verificado');
 await page.getByRole('link',{name:'Entrar',exact:true}).click();
 await page.locator('#email').fill(email);
 await page.locator('#password').fill(password);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.waitForURL('**/dashboard.html');
 await page.getByText('Olá, Estudante.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Perfil',exact:true}).click();
 await page.getByRole('heading',{name:'Seu perfil',exact:true}).waitFor();
 await page.locator('[name=name]').waitFor();
 assert.equal(await page.locator('[name=name]').inputValue(),'Estudante Navegador');
 assert.equal(await page.locator('[name=periodNumber]').inputValue(),'3');
 assert.equal(await page.locator('[name=shift]').inputValue(),'night');
 await mkdir('docs/previews/java-connected',{recursive:true});
 await page.screenshot({path:'docs/previews/java-connected/profile-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'docs/previews/java-connected/profile-mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile must not overflow');
 await page.getByRole('button',{name:'Início',exact:true}).click();
 await page.getByText('Olá, Estudante.',{exact:true}).waitFor();
 await page.screenshot({path:'docs/previews/java-connected/home-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'docs/previews/java-connected/home-desktop.png',fullPage:true});
 await page.goto(origin+'/login.html#recuperar');
 await page.locator('#email').fill(email);
 await page.getByRole('button',{name:'Enviar instruções',exact:true}).click();
 await page.getByRole('heading',{name:'Confira as instruções.',exact:true}).waitFor();
 const resetUrl=await authLink(env.pool,email,'reset_password');
 await page.goto(resetUrl);
 await page.locator('#password').fill('Senha-redefinida-2026');
 await page.locator('#confirm').fill('Senha-redefinida-2026');
 await page.getByRole('button',{name:'Salvar nova senha',exact:true}).click();
 await page.getByRole('heading',{name:'Senha alterada.',exact:true}).waitFor();
 await page.goto(origin+'/dashboard.html');
 await page.waitForURL('**/login.html#login');
 await page.locator('#email').fill(email);
 await page.locator('#password').fill(password);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.locator('#feedback').getByText('E-mail ou senha incorretos.',{exact:true}).waitFor();
 await page.locator('#password').fill('Senha-redefinida-2026');
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.waitForURL('**/dashboard.html');
 await page.getByText('Olá, Estudante.',{exact:true}).waitFor();
 assert.deepEqual(errors,[],'browser must have no JavaScript exceptions');
});
