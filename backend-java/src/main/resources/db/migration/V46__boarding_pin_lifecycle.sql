-- Boarding credentials are operational secrets, not permanent contract proof.
-- Freeze the original campus-day deadline; later edits must not renew it.
ALTER TABLE ride_reservations ADD COLUMN pin_expires_at timestamptz;
ALTER TABLE ride_reservations ADD COLUMN pin_erased_at timestamptz;
UPDATE ride_reservations rr SET pin_expires_at=((r.ride_date+1)::timestamp AT TIME ZONE un.time_zone)
 FROM rides r JOIN universities un ON un.id=r.university_id WHERE r.id=rr.ride_id;
ALTER TABLE ride_reservations ALTER COLUMN pin_expires_at SET NOT NULL;
ALTER TABLE ride_reservations ALTER COLUMN pin_ciphertext DROP NOT NULL;
ALTER TABLE ride_reservations ALTER COLUMN pin_hash DROP NOT NULL;
ALTER TABLE ride_reservations ADD CONSTRAINT reservation_pin_pair CHECK(
 (pin_erased_at IS NULL AND pin_ciphertext IS NOT NULL AND pin_hash IS NOT NULL)
 OR (pin_erased_at IS NOT NULL AND pin_ciphertext IS NULL AND pin_hash IS NULL));

CREATE FUNCTION privacy_boarding_pin_window(rr ride_reservations) RETURNS boolean
LANGUAGE sql STABLE STRICT AS $$
 SELECT rr.status='confirmed' AND rr.boarded_at IS NULL AND rr.pin_expires_at>clock_timestamp()
   AND EXISTS(SELECT 1 FROM rides r JOIN universities un ON un.id=r.university_id WHERE r.id=rr.ride_id
     AND r.status IN ('planned','active') AND r.ride_date>=(clock_timestamp() AT TIME ZONE un.time_zone)::date)
   AND EXISTS(SELECT 1 FROM users u WHERE u.id=rr.passenger_id AND u.deleted_at IS NULL AND u.account_status<>'deleted')
   AND EXISTS(SELECT 1 FROM users u WHERE u.id=rr.driver_id AND u.deleted_at IS NULL AND u.account_status<>'deleted')
$$;
CREATE FUNCTION privacy_boarding_pin_available(rr ride_reservations) RETURNS boolean
LANGUAGE sql STABLE STRICT AS $$
 SELECT privacy_boarding_pin_window(rr) AND rr.pin_erased_at IS NULL AND rr.pin_ciphertext IS NOT NULL AND rr.pin_hash IS NOT NULL
$$;

CREATE OR REPLACE FUNCTION reservation_state_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE original_deadline timestamptz; needed boolean;
BEGIN
 IF TG_OP='INSERT' THEN
   IF NEW.status<>'confirmed' THEN RAISE EXCEPTION 'Reservation must start confirmed' USING ERRCODE='23514'; END IF;
   IF NEW.boarded_at IS NOT NULL THEN RAISE EXCEPTION 'A new reservation cannot invent boarding evidence' USING ERRCODE='23514'; END IF;
   SELECT ((r.ride_date+1)::timestamp AT TIME ZONE un.time_zone) INTO original_deadline
     FROM rides r JOIN universities un ON un.id=r.university_id WHERE r.id=NEW.ride_id;
   IF NEW.pin_expires_at IS NOT NULL AND NEW.pin_expires_at IS DISTINCT FROM original_deadline THEN
     RAISE EXCEPTION 'PIN deadline must use the original campus day' USING ERRCODE='23514';
   END IF;
   NEW.pin_expires_at:=original_deadline;
   IF NEW.pin_erased_at IS NOT NULL THEN RAISE EXCEPTION 'PIN erasure metadata is generated by its lifecycle' USING ERRCODE='23514'; END IF;
 ELSE
   IF ROW(OLD.id,OLD.request_id,OLD.ride_id,OLD.passenger_id,OLD.driver_id,OLD.subscription_id,OLD.payment_id,OLD.price_cents,OLD.created_at,OLD.pin_expires_at)
     IS DISTINCT FROM ROW(NEW.id,NEW.request_id,NEW.ride_id,NEW.passenger_id,NEW.driver_id,NEW.subscription_id,NEW.payment_id,NEW.price_cents,NEW.created_at,NEW.pin_expires_at)
     THEN RAISE EXCEPTION 'Immutable reservation contract and PIN deadline' USING ERRCODE='23514'; END IF;
   IF OLD.status<>NEW.status AND NOT (
     (OLD.status='confirmed' AND NEW.status IN ('boarded','awaiting_confirmation','under_review','cancelled')) OR
     (OLD.status='boarded' AND NEW.status IN ('awaiting_confirmation','under_review','cancelled')) OR
     (OLD.status='awaiting_confirmation' AND NEW.status IN ('completed','under_review','cancelled')) OR
     (OLD.status='under_review' AND NEW.status IN ('completed','cancelled'))
   ) THEN RAISE EXCEPTION 'Invalid reservation transition' USING ERRCODE='23514'; END IF;
   IF OLD.boarded_at IS NOT NULL AND OLD.boarded_at IS DISTINCT FROM NEW.boarded_at THEN
     RAISE EXCEPTION 'Existing boarding evidence is immutable' USING ERRCODE='23514';
   END IF;
   IF OLD.boarded_at IS NULL AND NEW.boarded_at IS NOT NULL AND (OLD.status<>'confirmed' OR NEW.status<>'boarded') THEN
     RAISE EXCEPTION 'New boarding evidence requires its boarding transition' USING ERRCODE='23514';
   END IF;
   IF NEW.status='boarded' AND OLD.status<>'boarded' AND NEW.boarded_at IS NULL THEN
     RAISE EXCEPTION 'Boarding requires its evidence timestamp' USING ERRCODE='23514';
   END IF;
   IF NEW.status='boarded' AND OLD.status<>'boarded' AND NOT privacy_boarding_pin_available(OLD) THEN
     RAISE EXCEPTION 'An expired or erased PIN cannot authorize boarding' USING ERRCODE='23514';
   END IF;
   IF NEW.pin_erased_at IS DISTINCT FROM OLD.pin_erased_at THEN
     RAISE EXCEPTION 'PIN erasure metadata is immutable and lifecycle generated' USING ERRCODE='23514';
   END IF;
 END IF;
 needed:=privacy_boarding_pin_window(NEW);
 IF TG_OP='UPDATE' AND ROW(OLD.pin_ciphertext,OLD.pin_hash) IS DISTINCT FROM ROW(NEW.pin_ciphertext,NEW.pin_hash)
   AND NOT (OLD.pin_erased_at IS NULL AND NEW.pin_ciphertext IS NULL AND NEW.pin_hash IS NULL AND NOT needed) THEN
     RAISE EXCEPTION 'PIN replacement or premature erasure is forbidden' USING ERRCODE='23514';
 END IF;
 IF TG_OP='UPDATE' AND OLD.pin_erased_at IS NOT NULL THEN
   IF NEW.pin_ciphertext IS NOT NULL OR NEW.pin_hash IS NOT NULL THEN RAISE EXCEPTION 'An erased PIN cannot return' USING ERRCODE='23514'; END IF;
 ELSIF NOT needed THEN
   NEW.pin_ciphertext:=NULL;NEW.pin_hash:=NULL;NEW.pin_erased_at:=clock_timestamp();
 ELSIF NEW.pin_ciphertext IS NULL OR NEW.pin_hash IS NULL OR NEW.pin_ciphertext='' OR NEW.pin_hash='' THEN
   RAISE EXCEPTION 'Available boarding requires its original complete credential' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION privacy_ride_pin_invalidation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status NOT IN ('planned','active') THEN
   UPDATE ride_reservations SET pin_ciphertext=NULL,pin_hash=NULL
     WHERE ride_id=NEW.id AND pin_erased_at IS NULL;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER privacy_ride_pin_invalidation AFTER UPDATE OF status ON rides
 FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status) EXECUTE FUNCTION privacy_ride_pin_invalidation();
CREATE INDEX privacy_boarding_pin_expiry ON ride_reservations(pin_expires_at,id) WHERE pin_erased_at IS NULL;
